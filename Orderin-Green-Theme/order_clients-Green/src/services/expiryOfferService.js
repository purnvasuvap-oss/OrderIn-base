// src/services/expiryOfferService.js
// Expiry offers: discount a dish that uses stock which is about to expire,
// and publish a one-day promotion for it.
//
// Applying an offer writes the reduced price into the dish's `price`, so the
// customer app, cart and checkout charge it without any other change. The
// real price is kept in `offer.originalPrice`; the customer menu shows it
// struck through next to the offer price. When the offer ends, the price is
// put back (revertExpiredOffers runs whenever the Inventory or Menu page opens).

import { db } from "../firebase";
import { collection, doc, getDocs, updateDoc, addDoc, deleteField, Timestamp } from "firebase/firestore";
import { RESTAURANT_PATH } from "./inventoryBatchService";
import {
  applyPercent,
  buildOfferPromotionText,
  isOfferExpired,
  parseMoney,
  percentFromPrices,
} from "../utils/expiryOffers";

const menuCol = () => collection(db, RESTAURANT_PATH, "menu");
const promotionsCol = () => collection(db, RESTAURANT_PATH, "promotions");

export const DEFAULT_OFFER_HOURS = 24;

export const fetchMenuItems = async () => {
  const snap = await getDocs(menuCol());
  return snap.docs.map((d) => ({ id: d.id, ...d.data() }));
};

const priceString = (n) => String(Math.round(Number(n) || 0));

/**
 * Apply an offer to a dish and create a one-day promotion for it.
 * Pass either `percent` or `offerPrice` (offerPrice wins when both are given).
 */
export const applyExpiryOffer = async ({
  menuItem,
  percent,
  offerPrice,
  durationHours = DEFAULT_OFFER_HOURS,
  ingredients = [],
  createPromotion = true,
}) => {
  if (!menuItem?.id) throw new Error("Pick a dish first.");

  const running = menuItem.offer && !isOfferExpired(menuItem);
  const originalPrice = running ? parseMoney(menuItem.offer.originalPrice) : parseMoney(menuItem.price);
  if (!originalPrice) throw new Error(`${menuItem.name} has no price set.`);

  const finalPrice = offerPrice != null && offerPrice !== "" ? Math.round(parseMoney(offerPrice)) : applyPercent(originalPrice, percent);
  if (!(finalPrice > 0) || finalPrice >= originalPrice) {
    throw new Error("The offer price must be more than ₹0 and less than the current price.");
  }
  const pct = percentFromPrices(originalPrice, finalPrice);

  const now = Timestamp.now();
  const endsAt = Timestamp.fromMillis(now.toMillis() + Number(durationHours || DEFAULT_OFFER_HOURS) * 3600000);
  const ingredientNames = ingredients.map((i) => i.itemName || i.name).filter(Boolean);

  let promotionId = running ? menuItem.offer.promotionId || null : null;
  if (createPromotion) {
    const { caption, description } = buildOfferPromotionText({
      dishName: menuItem.name,
      originalPrice,
      offerPrice: finalPrice,
      percent: pct,
    });
    // image_url only (no image_path): the Promotions page deletes the stored
    // image of an expired promotion by its path, and this image is the dish's
    // own menu photo, which must stay.
    const promoRef = await addDoc(promotionsCol(), {
      image_url: menuItem.image_url || menuItem.image || menuItem.imageURL || null,
      caption,
      description,
      duration: `${durationHours}h`,
      createdAt: now,
      expiryAt: endsAt,
      isActive: true,
      createdBy: "auto-expiry-offer",
      autoGenerated: true,
      reason: "expiry_offer",
      linkedMenuItemId: menuItem.id,
      linkedMenuItemName: menuItem.name,
      originalPrice,
      discountedPrice: finalPrice,
      discountPercent: pct,
      sourceInventoryItems: ingredientNames,
    });
    promotionId = promoRef.id;
  }

  const offer = {
    active: true,
    source: "expiry",
    originalPrice,
    offerPrice: finalPrice,
    percent: pct,
    startsAt: now,
    endsAt,
    promotionId,
    ingredients: ingredientNames,
  };
  await updateDoc(doc(menuCol(), menuItem.id), { price: priceString(finalPrice), offer });
  return { ...offer, menuItemId: menuItem.id };
};

/** End a dish's offer now and put its price back. */
export const endExpiryOffer = async (menuItem) => {
  if (!menuItem?.id || !menuItem.offer) return false;
  const update = { offer: deleteField() };
  // Only restore the price if staff didn't change it by hand during the offer.
  if (parseMoney(menuItem.price) === parseMoney(menuItem.offer.offerPrice)) {
    update.price = priceString(menuItem.offer.originalPrice);
  }
  await updateDoc(doc(menuCol(), menuItem.id), update);
  return true;
};

/**
 * Put prices back for every offer whose time is up. No scheduled function
 * (see BILLING_GUARD.md), so this runs when staff open Inventory or Menu, and
 * the customer app separately ignores an offer price once endsAt has passed.
 */
export const revertExpiredOffers = async (menuItems = null) => {
  const items = menuItems || (await fetchMenuItems());
  const due = items.filter((m) => m.offer && isOfferExpired(m));
  let reverted = 0;
  for (const m of due) {
    try {
      if (await endExpiryOffer(m)) reverted += 1;
    } catch (e) {
      console.error(`Could not end the offer on ${m.name}:`, e);
    }
  }
  return reverted;
};
